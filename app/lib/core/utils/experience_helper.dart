
/// ExperienceHelper provides utility methods for formatting and displaying
/// experience-related data in human-readable formats.
class ExperienceHelper {
  
  
  
  /// Returns the feed action text for experience creation events.
  ///
  /// Returns "shared an experience" to be displayed in feed headers
  /// like "Alice shared an experience".
  static String getFeedActionText() {
    return 'shared an experience';
  }
}
